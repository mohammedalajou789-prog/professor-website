// Pre-renders the Python figures of the built-in example sheets (docs/mn) so the
// sheet guide shows them instantly. Needs local Python 3 + numpy + matplotlib + mpmath (+ scipy).
//   node scripts/gen-sample-figs.mjs
import { createJiti } from 'jiti'
import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdtempSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const jiti = createJiti(import.meta.url, { alias: { '@': join(process.cwd(), 'src') } })
const { parseMN, collectPy } = await jiti.import(join(process.cwd(), 'src/lib/mn/parse.ts'))
const { SAMPLES } = await jiti.import(join(process.cwd(), 'src/lib/mn/samples.ts'))
const prelude = readFileSync('src/lib/py/prelude.ts', 'utf8').match(/String\.raw`([\s\S]*)`\s*$/)[1]

const figs = new Map()
for (const s of Object.values(SAMPLES)) for (const f of collectPy(parseMN(s.src))) figs.set(f.hash, f.code)

const dir = mkdtempSync(join(tmpdir(), 'mnfig-'))
writeFileSync(join(dir, 'prelude.py'), prelude)
writeFileSync(join(dir, 'jobs.json'), JSON.stringify([...figs.entries()]))
writeFileSync(join(dir, 'run.py'), `
import json, sys
exec(open(sys.argv[1] + '/prelude.py').read())
out = {}
for h, code in json.load(open(sys.argv[1] + '/jobs.json')):
    try:
        out[h] = __mn_run(code)
    except Exception as e:
        print('skip', h, e, file=sys.stderr)
json.dump(out, open(sys.argv[1] + '/out.json', 'w'))
`)
execFileSync('python3', [join(dir, 'run.py'), dir], { stdio: 'inherit' })
const raw = JSON.parse(readFileSync(join(dir, 'out.json'), 'utf8'))

// same clean-up as the browser (src/lib/py/client.ts → scopeSvg)
const scope = (svg, hash) => {
  const P = `f${hash.slice(0, 10)}-`
  return svg
    .replace(/<\?xml[^>]*\?>\s*/g, '').replace(/<!DOCTYPE[^>]*>\s*/gi, '').replace(/<metadata>[\s\S]*?<\/metadata>\s*/g, '')
    .replace(/<style[^>]*>[\s\S]*?<\/style>\s*/g, '')
    .replace(/<svg\b/, '<svg style="stroke-linejoin:round;stroke-linecap:butt"')
    .replace(/\bid="([^"]+)"/g, `id="${P}$1"`)
    .replace(/((?:xlink:)?href)="#([^"]+)"/g, `$1="#${P}$2"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${P}$1)`)
    .trim()
}
const out = Object.fromEntries(Object.entries(raw).map(([h, s]) => [h, scope(s, h)]))
writeFileSync('src/lib/mn/sample-figs.ts', `// Generated by scripts/gen-sample-figs.mjs — Python figures of the example sheets (instant in the sheet guide)\nexport const SAMPLE_FIGS: Record<string, string> = ${JSON.stringify(out)}\n`)
console.log('sample-figs.ts:', Object.keys(out).length, 'figures,', Math.round(JSON.stringify(out).length / 1024), 'KB')
